"""Step 12.2 — Create a matching function"""

def find_ride_matches(
    data,
    booking_id,
    time_window_minutes=30,
    max_matches=5
):

    passenger = data[
        data["booking_id"] == booking_id
    ]

    if passenger.empty:
        return pd.DataFrame()

    passenger = passenger.iloc[0]

    candidates = data[
        (data["booking_id"] != booking_id)
        & (
            data["pickup_location"]
            == passenger["pickup_location"]
        )
        & (
            data["drop_location"]
            == passenger["drop_location"]
        )
    ].copy()

    candidates["time_difference_minutes"] = (
        candidates["departure_datetime"]
        - passenger["departure_datetime"]
    ).abs().dt.total_seconds() / 60

    matches = candidates[
        candidates["time_difference_minutes"]
        <= time_window_minutes
    ]

    return matches.sort_values(
        "time_difference_minutes"
    ).head(max_matches)

